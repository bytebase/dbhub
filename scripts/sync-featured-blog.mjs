import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

export function selectFeaturedPost(posts) {
  const featured = [];
  for (const { slug, content } of posts) {
    const frontmatter = content.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
    if (!frontmatter) throw new Error(`${slug}: missing frontmatter`);
    const metadata = parse(frontmatter[1]);
    if (metadata.featured !== undefined && typeof metadata.featured !== "boolean") {
      throw new Error(`${slug}: featured must be a boolean`);
    }
    if (!metadata.featured) continue;
    const { title, date } = metadata;
    if (typeof title !== "string" || !title.trim()) {
      throw new Error(`${slug}: featured posts need a title`);
    }
    if (
      typeof date !== "string" ||
      !/^\d{4}-\d{2}-\d{2}$/.test(date) ||
      !Number.isFinite(Date.parse(date)) ||
      new Date(date).toISOString().slice(0, 10) !== date
    ) {
      throw new Error(`${slug}: featured posts need a valid date in YYYY-MM-DD format`);
    }
    featured.push({ slug, title, date });
  }
  return featured.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug))[0];
}

export function renderFeaturedBlog(post) {
  const header = "// Generated by pnpm sync:featured-blog. Edit blog frontmatter instead.\n";
  if (!post) return `${header}export const FeaturedBlog = () => null;\n`;
  const dateLabel = new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(post.date));
  return `${header}export const FeaturedBlog = () => (\n  <a className="dbhub-blog-pill" href={${JSON.stringify(`/blog/${post.slug}`)}}>\n    <time className="dbhub-blog-pill-label" dateTime={${JSON.stringify(post.date)}}>{${JSON.stringify(dateLabel)}}</time>\n    <span>{${JSON.stringify(post.title)}}</span>\n    <span aria-hidden="true">→</span>\n  </a>\n);\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const blog = resolve(root, "docs/blog");
  const posts = readdirSync(blog, { recursive: true })
    .filter((file) => /\.mdx?$/.test(file))
    .map((file) => ({
      slug: file.replace(/\.mdx?$/, ""),
      content: readFileSync(resolve(blog, file), "utf8"),
    }));
  const output = resolve(root, "docs/snippets/featured-blog.jsx");
  const content = renderFeaturedBlog(selectFeaturedPost(posts));
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== content) {
      throw new Error(
        "Featured blog pill is stale. Run pnpm sync:featured-blog and commit the result."
      );
    }
  } else {
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, content);
  }
}
